// 一言（quick）の危機の言葉の検出（PLAN 85・憲法第8条）。純粋関数。
// 一言は AI を通らないので、サーバーで決まった言葉を見つけたら、AI を呼ばずに窓口を案内する（保存は成功させる）。
// 表記ゆれ（全角/半角・カタカナ/ひらがな・小さい母音・伸ばし棒・空白）をならしてから照らす。
// 誤検知しすぎない：「忙しくて死にそう」「死ぬほど笑った」「わたしにたいして」「学校いきたくない」などは拾わない。
// 迷う表現は、案内を出す側に倒す（案内は診断ではなく、窓口を知らせるだけなので害が小さい）。

const SMALL_VOWELS: Record<string, string> = { ぁ: "あ", ぃ: "い", ぅ: "う", ぇ: "え", ぉ: "お" };

/** 照合用にならす：NFKC・小文字・カタカナ→ひらがな・小さい母音→普通・空白と伸ばし棒などを除く */
export function normalizeForCrisis(text: string): string {
  return text
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .replace(/[ぁぃぅぇぉ]/g, (ch) => SMALL_VOWELS[ch] ?? ch)
    .replace(/[\s　ー〜~・…‥_]+/g, "");
}

// 「〜たく」のあとの打ち消し（死にたくない・死にたくなかった・死にたくなければ）は拾わない
const NOT_NEG = "(?!な[いかけ])";

const PATTERNS: RegExp[] = [
  // 死にたい（漢字は「死にたいし、」も拾う）
  new RegExp(`死にた(い|く${NOT_NEG})`),
  /死にてえ/,
  // ひらがな・当て字（しにたい／氏にたい／タヒにたい）。「わたしにたいして」「わたしにたくさん」は除く
  new RegExp(`(し|氏|たひ)にた(い(?![しすせ])|く(?!な[いかけ]|さん|わえ|し))`),
  /しにてえ|たひたい/,
  /(死|し)んで(しま|ちゃ)いたい|(死|し)んじゃいたい|(死|し)んでしまおう/,
  /(死|し)んだ(ほう|方)が(まし|楽|らく|いい)/,
  /死のう(かな|と思|って思|とした)/,
  /死なせて(ほしい|くれ|ください)/,
  // 消えたい・いなくなりたい
  new RegExp(`(消|き)え(て(しまい|ちゃい|なくなり)|ちゃい)?た(い|く${NOT_NEG})`),
  /消えてえ/,
  /(い|居)なくなりたい/,
  // 自殺・自傷
  /自殺|じさつ/,
  /自傷/,
  /りすとかっと|りすか(?=し|の|跡|痕|あと|$)/,
  /手首を?切/,
  /自分を傷つけ/,
  /おばどず|過剰服薬|(^|[^a-z])od(し|した|しそう|しちゃ)/,
  // 首を吊る（「首をつっこむ」は除く）
  /首を?吊|首つり|くびつり|首をつ(り|る|ろう|った)/,
  /(飛び?降|とびお)り(たい|よう)/,
  /(電車|線路)に(飛び?込|とびこ)(み|も|ん)/,
  // 生きていたくない（「学校いきたくない」は除くため、ひらがなは「いきていたくない」だけ）
  /生き(てい|て)?たくない|いきて(い)?たくない/,
  /生き(る|てる|ている|てく|ていく)意味(が|も|なんて)?(ない|無い)/,
];

/** 一言に危機の言葉が含まれるか（true なら窓口を案内する） */
export function detectCrisis(text: string): boolean {
  const s = normalizeForCrisis(text);
  if (!s) return false;
  return PATTERNS.some((re) => re.test(s));
}
